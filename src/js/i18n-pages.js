function getPagesLang() {
  try {
    const s = JSON.parse(localStorage.getItem('darkSnowFConfig') || '{}');
    if (s.lang === 'en' || s.lang === 'es') return s.lang;
  } catch (e) {}
  // Sin elección guardada: idioma del equipo.
  if (typeof window.dsSysLang === 'function') return window.dsSysLang();
  return 'es';
}

function tP(key) {
  const lang = getPagesLang();
  if (PAGES_STRINGS[lang] && PAGES_STRINGS[lang][key] !== undefined) {
    return PAGES_STRINGS[lang][key];
  }
  return PAGES_STRINGS.es[key] !== undefined ? PAGES_STRINGS.es[key] : key;
}

function applyPagesLang() {
  const lang = getPagesLang();
  const dict = PAGES_STRINGS[lang] || PAGES_STRINGS.es;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-pi18n]').forEach((el) => {
    const key = el.getAttribute('data-pi18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-pi18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-pi18n-ph');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', applyPagesLang);
} else {
  applyPagesLang();
}
